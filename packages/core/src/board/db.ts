import { Database } from 'bun:sqlite';
import { drizzle } from 'drizzle-orm/bun-sqlite';
import { migrate as migrateUp } from 'drizzle-orm/bun-sqlite/migrator';
import * as tables from './schema.js';

/**
 * The board's database wiring.
 *
 * The tables are declared in `schema.ts`, driver-free, so `drizzle-kit
 * generate` can load it under node; this file opens the database with
 * bun:sqlite and applies the generated migrations.
 *
 * bun:sqlite is the driver because the OpenCode plugin runtime is Bun: the
 * adapter opens the same database the board server writes, and a driver one
 * runtime lacks breaks the other.
 */

const schema = {
  records: tables.records,
  record_reads: tables.recordReads,
  leases: tables.leases,
  budgets: tables.budgets,
};

export type BoardDatabase = ReturnType<typeof drizzle<typeof schema>>;

/** Open the board's database, with the pragmas a local board wants. */
export function openDatabase(path: string): BoardDatabase {
  const sqlite = new Database(path);
  sqlite.exec('PRAGMA journal_mode = WAL');
  sqlite.exec('PRAGMA foreign_keys = ON');
  sqlite.exec('PRAGMA busy_timeout = 5000');
  return drizzle(sqlite, { schema });
}

/** Close the board's database. The drizzle handle hides the driver, so this is the one close. */
export function closeDatabase(db: BoardDatabase): void {
  (db.$client as Database).close();
}

/**
 * Bring the database up to the schema.
 *
 * The migrations live in `drizzle/`, generated by `drizzle-kit generate`
 * from the declaration in `schema.ts`, and the migrator applies the ones
 * the database has not recorded yet.
 */
export function migrate(db: BoardDatabase): void {
  migrateUp(db, { migrationsFolder: new URL('../../drizzle', import.meta.url).pathname });
}
